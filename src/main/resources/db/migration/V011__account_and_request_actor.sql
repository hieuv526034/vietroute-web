-- Không sửa mật khẩu/active/email các tài khoản đang có. Admin cũ tiếp tục đăng nhập bình thường.
ALTER TABLE auth_users ADD COLUMN email VARCHAR(254);
ALTER TABLE auth_users ADD COLUMN email_verified_at TIMESTAMPTZ;
ALTER TABLE auth_users ADD COLUMN activation_pending BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE auth_users ADD CONSTRAINT ck_auth_users_email CHECK (email IS NULL OR email = lower(email));
CREATE UNIQUE INDEX uq_auth_users_email ON auth_users(email) WHERE email IS NOT NULL;

-- Chỉ giữ hai hash cũ sau mỗi lần đổi; hash hiện tại vẫn ở auth_users.
CREATE TABLE auth_password_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES auth_users(id) CHECK (user_id > 0),
    password_hash VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id)
);
CREATE INDEX idx_auth_password_history_user ON auth_password_history(user_id, id DESC);
CREATE INDEX idx_auth_password_history_created_by ON auth_password_history(created_by);
CREATE INDEX idx_auth_password_history_updated_by ON auth_password_history(updated_by);

-- Mỗi user chỉ có một challenge mỗi mục đích, upsert thay mã cũ; không giữ token rõ trong bảng này.
CREATE TABLE auth_account_challenges (
    user_id BIGINT NOT NULL REFERENCES auth_users(id) CHECK (user_id > 0),
    purpose VARCHAR(16) NOT NULL CHECK (purpose IN ('ACTIVATE', 'RESET')),
    token_hash VARCHAR(64) NOT NULL,
    token_version BIGINT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    updated_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    PRIMARY KEY (user_id, purpose)
);
CREATE INDEX idx_auth_account_challenges_created_by ON auth_account_challenges(created_by);
CREATE INDEX idx_auth_account_challenges_updated_by ON auth_account_challenges(updated_by);

