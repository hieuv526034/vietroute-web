CREATE TABLE auth_roles (
    code VARCHAR(24) PRIMARY KEY,
    name_vi VARCHAR(120) NOT NULL,
    name_en VARCHAR(120) NOT NULL
);
CREATE TABLE auth_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(32) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    display_name VARCHAR(120) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    must_change_password BOOLEAN NOT NULL DEFAULT TRUE,
    failed_login_attempts INTEGER NOT NULL DEFAULT 0 CHECK (failed_login_attempts >= 0),
    locked_until TIMESTAMPTZ,
    token_version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT REFERENCES auth_users(id),
    updated_by BIGINT REFERENCES auth_users(id),
    version BIGINT NOT NULL DEFAULT 0,
    CHECK (username ~ '^[a-z][a-z0-9]{2,31}$')
);
CREATE TABLE auth_user_roles (
    user_id BIGINT NOT NULL REFERENCES auth_users(id),
    role_code VARCHAR(24) NOT NULL REFERENCES auth_roles(code),
    PRIMARY KEY (user_id, role_code)
);
CREATE TABLE catalog_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(32) NOT NULL CHECK (type IN ('VEHICLE_TYPE', 'BOOKING_SOURCE')),
    code VARCHAR(40) NOT NULL,
    name_vi VARCHAR(120) NOT NULL,
    name_en VARCHAR(120) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT REFERENCES auth_users(id),
    updated_by BIGINT REFERENCES auth_users(id),
    version BIGINT NOT NULL DEFAULT 0,
    UNIQUE (type, code),
    CHECK (code ~ '^[A-Z][A-Z0-9]{2,39}$')
);
CREATE INDEX idx_catalog_type_active_order ON catalog_items(type, active, sort_order, id);
