-- Nền phạm vi quản trị, chưa tạo dữ liệu nhà xe/chuyến/booking hoặc tự gán membership cho role hiện có.
CREATE TABLE auth_data_scopes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE CHECK (code ~ '^[A-Z][A-Z0-9_]{1,49}$'),
    name_vi VARCHAR(120) NOT NULL,
    name_en VARCHAR(120) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    updated_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_data_scopes_created_by ON auth_data_scopes(created_by);
CREATE INDEX idx_data_scopes_updated_by ON auth_data_scopes(updated_by);

CREATE TABLE auth_scope_memberships (
    scope_id BIGINT NOT NULL REFERENCES auth_data_scopes(id),
    user_id BIGINT NOT NULL REFERENCES auth_users(id) CHECK (user_id <> 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    updated_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    version BIGINT NOT NULL DEFAULT 1,
    PRIMARY KEY(scope_id,user_id)
);
CREATE INDEX idx_scope_memberships_user ON auth_scope_memberships(user_id,scope_id);
CREATE INDEX idx_scope_memberships_created_by ON auth_scope_memberships(created_by);
CREATE INDEX idx_scope_memberships_updated_by ON auth_scope_memberships(updated_by);

-- Role trong phạm vi phải được gán cho chính user ở tầng toàn hệ thống; thu hồi role toàn cục dọn mapping phạm vi.
CREATE TABLE auth_scope_roles (
    scope_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    role_code VARCHAR(24) NOT NULL CHECK (role_code <> 'ADMIN'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    updated_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY(scope_id,user_id,role_code),
    FOREIGN KEY(scope_id,user_id) REFERENCES auth_scope_memberships(scope_id,user_id) ON DELETE CASCADE,
    FOREIGN KEY(user_id,role_code) REFERENCES auth_user_roles(user_id,role_code) ON DELETE CASCADE
);
CREATE INDEX idx_scope_roles_user_role ON auth_scope_roles(user_id,role_code);
CREATE INDEX idx_scope_roles_created_by ON auth_scope_roles(created_by);
CREATE INDEX idx_scope_roles_updated_by ON auth_scope_roles(updated_by);
