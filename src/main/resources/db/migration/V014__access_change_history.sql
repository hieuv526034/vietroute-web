-- Lịch sử thay đổi quyền ghi trong cùng transaction nghiệp vụ; không backfill sự kiện giả cho dữ liệu cũ.
CREATE TABLE auth_access_changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type VARCHAR(64) NOT NULL CHECK (event_type ~ '^[A-Z][A-Z0-9_]{2,63}$'),
    target_kind VARCHAR(20) NOT NULL,
    target_key VARCHAR(240) NOT NULL,
    actor_id BIGINT NOT NULL REFERENCES auth_users(id),
    trace_id VARCHAR(64),
    before_state JSONB NOT NULL,
    after_state JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    updated_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    version BIGINT NOT NULL DEFAULT 0,
    CHECK (jsonb_typeof(before_state) = 'object' AND jsonb_typeof(after_state) = 'object')
);
CREATE INDEX idx_access_changes_time ON auth_access_changes(created_at, id);
CREATE INDEX idx_access_changes_target ON auth_access_changes(target_kind, target_key, created_at);
CREATE INDEX idx_access_changes_actor ON auth_access_changes(actor_id, created_at);
CREATE INDEX idx_access_changes_trace ON auth_access_changes(trace_id);
CREATE INDEX idx_access_changes_created_by ON auth_access_changes(created_by);
CREATE INDEX idx_access_changes_updated_by ON auth_access_changes(updated_by);
