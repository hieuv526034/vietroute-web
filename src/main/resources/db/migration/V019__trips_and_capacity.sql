-- Chuyến giữ snapshot tuyến/địa điểm/giá; cập nhật mẫu không thay lịch sử chuyến.
CREATE TABLE carrier_trips (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carrier_id BIGINT NOT NULL,
    scope_id BIGINT NOT NULL,
    route_id BIGINT NOT NULL,
    vehicle_id BIGINT NOT NULL,
    driver_id BIGINT NOT NULL,
    driver_user_id BIGINT NOT NULL REFERENCES auth_users(id) CHECK(driver_user_id>0),
    code VARCHAR(40) NOT NULL CHECK(code ~ '^[A-Z][A-Z0-9]{2,39}$'),
    name_vi VARCHAR(160) NOT NULL,
    name_en VARCHAR(160) NOT NULL,
    plate_number VARCHAR(20) NOT NULL,
    vehicle_type_id BIGINT NOT NULL REFERENCES catalog_items(id),
    vehicle_type_name_vi VARCHAR(120) NOT NULL,
    vehicle_type_name_en VARCHAR(120) NOT NULL,
    driver_name VARCHAR(120) NOT NULL,
    driver_phone VARCHAR(30) NOT NULL,
    departure_at TIMESTAMPTZ NOT NULL,
    end_at TIMESTAMPTZ NOT NULL CHECK(end_at>departure_at),
    capacity INTEGER NOT NULL CHECK(capacity BETWEEN 1 AND 200),
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK(status IN('DRAFT','OPEN','IN_PROGRESS','COMPLETED','CANCELLED')),
    operation_note VARCHAR(2000) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    updated_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
    FOREIGN KEY(carrier_id,scope_id) REFERENCES carriers(id,scope_id),
    FOREIGN KEY(route_id,carrier_id,scope_id) REFERENCES carrier_routes(id,carrier_id,scope_id),
    FOREIGN KEY(vehicle_id,carrier_id,scope_id) REFERENCES carrier_vehicles(id,carrier_id,scope_id),
    FOREIGN KEY(driver_id,carrier_id,scope_id) REFERENCES carrier_drivers(id,carrier_id,scope_id),
    UNIQUE(carrier_id,code),
    UNIQUE(id,carrier_id,scope_id)
);
CREATE INDEX idx_trips_carrier_status ON carrier_trips(carrier_id,status,departure_at,id);
CREATE INDEX idx_trips_vehicle_schedule ON carrier_trips(vehicle_id,departure_at,end_at) WHERE status IN('OPEN','IN_PROGRESS');
CREATE INDEX idx_trips_driver_schedule ON carrier_trips(driver_id,departure_at,end_at) WHERE status IN('OPEN','IN_PROGRESS');
CREATE INDEX idx_trips_driver_user ON carrier_trips(driver_user_id,status,departure_at);
CREATE INDEX idx_trips_route ON carrier_trips(route_id);
CREATE INDEX idx_trips_created_by ON carrier_trips(created_by);
CREATE INDEX idx_trips_updated_by ON carrier_trips(updated_by);

CREATE TABLE trip_stops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id BIGINT NOT NULL,
    carrier_id BIGINT NOT NULL,
    scope_id BIGINT NOT NULL,
    location_id BIGINT NOT NULL REFERENCES location_places(id),
    province_id BIGINT NOT NULL REFERENCES location_provinces(id),
    stop_order INTEGER NOT NULL CHECK(stop_order BETWEEN 1 AND 32),
    name_vi VARCHAR(120) NOT NULL,
    name_en VARCHAR(120) NOT NULL,
    address VARCHAR(300) NOT NULL,
    latitude NUMERIC(9,6) NOT NULL CHECK(latitude BETWEEN -90 AND 90),
    longitude NUMERIC(9,6) NOT NULL CHECK(longitude BETWEEN -180 AND 180),
    scheduled_arrival_at TIMESTAMPTZ NOT NULL,
    scheduled_departure_at TIMESTAMPTZ NOT NULL CHECK(scheduled_departure_at>=scheduled_arrival_at),
    actual_arrival_at TIMESTAMPTZ,
    actual_departure_at TIMESTAMPTZ CHECK(actual_departure_at IS NULL OR (actual_arrival_at IS NOT NULL AND actual_departure_at>=actual_arrival_at)),
    cumulative_fare NUMERIC(12,2) NOT NULL CHECK(cumulative_fare>=0),
    pickup_allowed BOOLEAN NOT NULL,
    dropoff_allowed BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    updated_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
    FOREIGN KEY(trip_id,carrier_id,scope_id) REFERENCES carrier_trips(id,carrier_id,scope_id),
    UNIQUE(trip_id,stop_order),
    UNIQUE(trip_id,location_id),
    UNIQUE(id,trip_id,carrier_id,scope_id)
);
CREATE INDEX idx_trip_stops_search ON trip_stops(location_id,scheduled_departure_at,trip_id);
CREATE INDEX idx_trip_stops_province_search ON trip_stops(province_id,scheduled_departure_at,trip_id);
CREATE INDEX idx_trip_stops_created_by ON trip_stops(created_by);
CREATE INDEX idx_trip_stops_updated_by ON trip_stops(updated_by);

CREATE TABLE trip_segments (
    trip_id BIGINT NOT NULL,
    carrier_id BIGINT NOT NULL,
    scope_id BIGINT NOT NULL,
    segment_order INTEGER NOT NULL CHECK(segment_order BETWEEN 1 AND 31),
    capacity INTEGER NOT NULL CHECK(capacity BETWEEN 1 AND 200),
    reserved_seats INTEGER NOT NULL DEFAULT 0 CHECK(reserved_seats BETWEEN 0 AND capacity),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
    PRIMARY KEY(trip_id,segment_order),
    FOREIGN KEY(trip_id,carrier_id,scope_id) REFERENCES carrier_trips(id,carrier_id,scope_id)
);
CREATE INDEX idx_trip_segments_updated_by ON trip_segments(updated_by);

CREATE TABLE trip_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id BIGINT NOT NULL,
    carrier_id BIGINT NOT NULL,
    scope_id BIGINT NOT NULL,
    stop_order INTEGER,
    event_type VARCHAR(30) NOT NULL CHECK(event_type IN('CREATED','OPENED','ASSIGNED','STARTED','ARRIVED','DEPARTED','COMPLETED','CANCELLED','NOTICE')),
    note VARCHAR(2000) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    FOREIGN KEY(trip_id,carrier_id,scope_id) REFERENCES carrier_trips(id,carrier_id,scope_id),
    FOREIGN KEY(trip_id,stop_order) REFERENCES trip_stops(trip_id,stop_order)
);
CREATE INDEX idx_trip_events_trip ON trip_events(trip_id,id);
CREATE INDEX idx_trip_events_created_by ON trip_events(created_by);
