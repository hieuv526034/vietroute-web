-- Registry mở rộng, vô hiệu hóa thay vì xóa để giữ FK và lịch sử audit.
ALTER TABLE auth_roles ADD COLUMN active BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE auth_roles ADD COLUMN registry_version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE auth_permissions ADD COLUMN active BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE auth_permissions ADD COLUMN registry_version BIGINT NOT NULL DEFAULT 0;
CREATE TABLE auth_access_policies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(12) NOT NULL CHECK (kind IN ('MENU','ENDPOINT')),
    target VARCHAR(240) NOT NULL,
    name_vi VARCHAR(160) NOT NULL,
    name_en VARCHAR(160) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    required_permissions TEXT NOT NULL DEFAULT '',
    allowed_roles TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    updated_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_access_policy_target UNIQUE(kind,target)
);
CREATE INDEX idx_access_policy_created_by ON auth_access_policies(created_by);
CREATE INDEX idx_access_policy_updated_by ON auth_access_policies(updated_by);
