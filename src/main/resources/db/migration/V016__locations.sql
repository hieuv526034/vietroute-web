-- Danh mục địa lý dùng chung; không seed tên/mã/tọa độ giả hoặc phụ thuộc nhà cung cấp bản đồ.
-- Chỉ ngừng sử dụng, không có luồng xóa vật lý; nghiệp vụ tuyến/chuyến phải tham chiếu ID và snapshot khi cần lịch sử.
CREATE TABLE location_provinces (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE CHECK (code ~ '^[A-Z][A-Z0-9]{2,39}$'),
    name_vi VARCHAR(120) NOT NULL CHECK (length(btrim(name_vi)) > 0),
    name_en VARCHAR(120) NOT NULL CHECK (length(btrim(name_en)) > 0),
    sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order BETWEEN 0 AND 10000),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    updated_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0)
);
CREATE INDEX idx_location_provinces_active ON location_provinces(active,sort_order,id);
CREATE INDEX idx_location_provinces_created_by ON location_provinces(created_by);
CREATE INDEX idx_location_provinces_updated_by ON location_provinces(updated_by);

CREATE TABLE location_places (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    province_id BIGINT NOT NULL REFERENCES location_provinces(id),
    code VARCHAR(40) NOT NULL UNIQUE CHECK (code ~ '^[A-Z][A-Z0-9]{2,39}$'),
    name_vi VARCHAR(120) NOT NULL CHECK (length(btrim(name_vi)) > 0),
    name_en VARCHAR(120) NOT NULL CHECK (length(btrim(name_en)) > 0),
    address VARCHAR(255) NOT NULL CHECK (length(btrim(address)) > 0),
    latitude NUMERIC(8,6) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude NUMERIC(9,6) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order BETWEEN 0 AND 10000),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    updated_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0)
);
CREATE INDEX idx_location_places_province ON location_places(province_id,active,sort_order,id);
CREATE INDEX idx_location_places_created_by ON location_places(created_by);
CREATE INDEX idx_location_places_updated_by ON location_places(updated_by);
