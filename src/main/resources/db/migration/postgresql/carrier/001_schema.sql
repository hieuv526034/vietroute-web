CREATE SEQUENCE IF NOT EXISTS carrier_scope_ids AS bigint START WITH 1 INCREMENT BY 1 MINVALUE 1 MAXVALUE 9223372036854775807 CACHE 1;

CREATE TABLE IF NOT EXISTS carrier_drivers (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    carrier_id bigint NOT NULL,
    scope_id bigint NOT NULL,
    code character varying(40) NOT NULL,
    name character varying(120) NOT NULL,
    phone character varying(30) NOT NULL,
    user_id bigint,
    active boolean DEFAULT true NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by bigint DEFAULT 0 NOT NULL,
    updated_by bigint DEFAULT 0 NOT NULL,
    version bigint DEFAULT 0 NOT NULL
);

CREATE TABLE IF NOT EXISTS carrier_vehicles (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    carrier_id bigint NOT NULL,
    scope_id bigint NOT NULL,
    code character varying(40) NOT NULL,
    plate_number character varying(20) NOT NULL,
    plate_key character varying(20) GENERATED ALWAYS AS (regexp_replace((plate_number)::text, '[^A-Z0-9]'::text, ''::text, 'g'::text)) STORED NOT NULL,
    vehicle_type_id bigint NOT NULL,
    vehicle_type character varying(40) DEFAULT 'VEHICLE_TYPE'::character varying NOT NULL,
    capacity integer NOT NULL,
    active boolean DEFAULT true NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by bigint DEFAULT 0 NOT NULL,
    updated_by bigint DEFAULT 0 NOT NULL,
    version bigint DEFAULT 0 NOT NULL
);

CREATE TABLE IF NOT EXISTS carriers (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    scope_id bigint NOT NULL,
    code character varying(40) NOT NULL,
    name character varying(120) NOT NULL,
    phone character varying(30) NOT NULL,
    description character varying(2000) DEFAULT ''::character varying NOT NULL,
    active boolean DEFAULT true NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by bigint DEFAULT 0 NOT NULL,
    updated_by bigint DEFAULT 0 NOT NULL,
    version bigint DEFAULT 0 NOT NULL,
    scope_code character varying(50) NOT NULL,
    scope_name_vi character varying(120) NOT NULL,
    scope_name_en character varying(120) NOT NULL,
    scope_active boolean DEFAULT true NOT NULL,
    scope_version bigint DEFAULT 0 NOT NULL
);

