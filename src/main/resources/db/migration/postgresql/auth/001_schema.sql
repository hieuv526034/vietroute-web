-- auth: bảng, khóa chính, ràng buộc và index hiện hành.
-- Schema lấy từ LOCAL search_path; khóa ngoại được tạo sau toàn bộ cụm.

CREATE TABLE IF NOT EXISTS auth_access_changes (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    event_type character varying(64) NOT NULL,
    target_kind character varying(20) NOT NULL,
    target_key character varying(240) NOT NULL,
    actor_id bigint NOT NULL,
    trace_id character varying(64),
    before_state jsonb NOT NULL,
    after_state jsonb NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by bigint DEFAULT 0 NOT NULL,
    updated_by bigint DEFAULT 0 NOT NULL,
    version bigint DEFAULT 0 NOT NULL
);

CREATE TABLE IF NOT EXISTS auth_account_challenges (
    user_id bigint NOT NULL,
    purpose character varying(16) NOT NULL,
    token_hash character varying(64) NOT NULL,
    token_version bigint NOT NULL,
    expires_at timestamp with time zone NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by bigint DEFAULT 0 NOT NULL,
    updated_by bigint DEFAULT 0 NOT NULL,
    id bigint GENERATED ALWAYS AS IDENTITY NOT NULL
);

CREATE TABLE IF NOT EXISTS auth_function_resources (
    function_code character varying(80) NOT NULL,
    kind character varying(12) NOT NULL,
    target character varying(240) NOT NULL,
    handler character varying(240) NOT NULL,
    description character varying(500) NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by bigint DEFAULT 0 NOT NULL,
    updated_by bigint DEFAULT 0 NOT NULL,
    version bigint DEFAULT 0 NOT NULL,
    http_method character varying(10) NOT NULL,
    path_template character varying(240) NOT NULL,
    name_vi character varying(500) DEFAULT ''::character varying NOT NULL,
    name_en character varying(500) DEFAULT ''::character varying NOT NULL,
    icon character varying(50) DEFAULT 'menu'::character varying NOT NULL,
    sort_order integer DEFAULT 0 NOT NULL,
    id bigint GENERATED ALWAYS AS IDENTITY NOT NULL
);

CREATE TABLE IF NOT EXISTS auth_functions (
    code character varying(80) NOT NULL,
    name_vi character varying(500) NOT NULL,
    name_en character varying(500) NOT NULL,
    active boolean DEFAULT true NOT NULL,
    deleted boolean DEFAULT false NOT NULL,
    version bigint DEFAULT 0 NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by bigint DEFAULT 0 NOT NULL,
    updated_by bigint DEFAULT 0 NOT NULL,
    description character varying(1000) DEFAULT ''::character varying NOT NULL,
    parent_code character varying(80),
    icon character varying(50) DEFAULT 'menu'::character varying NOT NULL,
    sort_order integer DEFAULT 0 NOT NULL,
    resources_initialized boolean DEFAULT false NOT NULL
);

CREATE TABLE IF NOT EXISTS auth_role_functions (
    role_code character varying(24) NOT NULL,
    function_code character varying(80) NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by bigint DEFAULT 0 NOT NULL,
    updated_by bigint DEFAULT 0 NOT NULL,
    version bigint DEFAULT 0 NOT NULL,
    id bigint GENERATED ALWAYS AS IDENTITY NOT NULL
);

CREATE TABLE IF NOT EXISTS auth_roles (
    code character varying(24) NOT NULL,
    name_vi character varying(120) NOT NULL,
    name_en character varying(120) NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_by bigint DEFAULT 0 NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by bigint DEFAULT 0 NOT NULL,
    active boolean DEFAULT true NOT NULL,
    deleted boolean DEFAULT false NOT NULL,
    functions_initialized boolean DEFAULT false NOT NULL,
    all_scopes boolean DEFAULT false NOT NULL,
    protected_role boolean DEFAULT false NOT NULL,
    version bigint DEFAULT 0 NOT NULL
);

CREATE TABLE IF NOT EXISTS auth_user_roles (
    user_id bigint NOT NULL,
    role_code character varying(24) NOT NULL,
    scope_id bigint DEFAULT 0 NOT NULL,
    active boolean DEFAULT true NOT NULL,
    version bigint DEFAULT 0 NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by bigint DEFAULT 0 NOT NULL,
    updated_by bigint DEFAULT 0 NOT NULL,
    global_scope_id bigint GENERATED ALWAYS AS (
CASE
    WHEN (scope_id > 0) THEN 0
    ELSE NULL::integer
END) STORED,
    carrier_scope_id bigint GENERATED ALWAYS AS (NULLIF(scope_id, 0)) STORED,
    id bigint GENERATED ALWAYS AS IDENTITY NOT NULL
);

CREATE TABLE IF NOT EXISTS auth_users (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    username character varying(32) NOT NULL,
    password_hash character varying(100) NOT NULL,
    display_name character varying(120) NOT NULL,
    active boolean DEFAULT true NOT NULL,
    must_change_password boolean DEFAULT true NOT NULL,
    failed_login_attempts integer DEFAULT 0 NOT NULL,
    locked_until timestamp with time zone,
    token_version bigint DEFAULT 0 NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by bigint DEFAULT 0 NOT NULL,
    updated_by bigint DEFAULT 0 NOT NULL,
    version bigint DEFAULT 0 NOT NULL,
    email character varying(254),
    email_verified_at timestamp with time zone,
    activation_pending boolean DEFAULT false NOT NULL,
    deleted boolean DEFAULT false NOT NULL,
    previous_password_hash_1 character varying(100),
    previous_password_hash_2 character varying(100),
    bootstrap_scope_pending boolean DEFAULT false NOT NULL,
    scope_membership_versions jsonb DEFAULT '{}'::jsonb NOT NULL
);

