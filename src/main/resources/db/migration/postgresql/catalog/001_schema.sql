CREATE INDEX IF NOT EXISTS idx_catalog_created_by ON catalog_items USING btree (created_by);

DO $$ DECLARE ns TEXT; BEGIN
    SELECT n.nspname INTO ns FROM pg_extension e JOIN pg_namespace n ON n.oid=e.extnamespace WHERE e.extname='pg_trgm';
    IF ns IS NULL THEN
        EXECUTE 'CREATE EXTENSION pg_trgm WITH SCHEMA ' || quote_ident(current_schema());
        ns := current_schema();
    END IF;
    EXECUTE format('CREATE INDEX IF NOT EXISTS idx_catalog_search_text ON catalog_items USING gin (lower((((((code)::text || '' ''::text) || (name_vi)::text) || '' ''::text) || (name_en)::text)) %I.gin_trgm_ops)', ns);
END $$;

