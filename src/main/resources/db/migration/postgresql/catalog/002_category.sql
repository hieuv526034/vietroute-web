-- Gộp danh mục; chạy trong transaction của migration, giữ audit và snapshot nghiệp vụ.
CREATE TABLE category (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(64) NOT NULL CHECK (code ~ '^[A-Z0-9][A-Z0-9_]{1,63}$'),
    type varchar(8) NOT NULL CHECK (type IN ('GROUP','VALUE')),
    name varchar(120) NOT NULL CHECK (length(btrim(name))>0),
    description varchar(1000) DEFAULT '' NOT NULL,
    ref_type varchar(64) NOT NULL,
    parent_id bigint REFERENCES category(id),
    props jsonb DEFAULT '{}'::jsonb NOT NULL CHECK (jsonb_typeof(props)='object'),
    active boolean DEFAULT true NOT NULL,
    sort_order integer DEFAULT 0 NOT NULL CHECK (sort_order BETWEEN 0 AND 10000),
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by bigint DEFAULT 0 NOT NULL REFERENCES auth_users(id),
    updated_by bigint DEFAULT 0 NOT NULL REFERENCES auth_users(id),
    version bigint DEFAULT 0 NOT NULL CHECK (version>=0),
    -- Khóa sinh chỉ đọc: FK nhóm không trỏ vào partial index.
    group_code varchar(64) GENERATED ALWAYS AS (CASE WHEN type='GROUP' THEN code END) STORED UNIQUE,
    value_ref varchar(64) GENERATED ALWAYS AS (CASE WHEN type='VALUE' THEN ref_type END) STORED,
    CONSTRAINT category_kind CHECK ((type='GROUP' AND ref_type=code AND parent_id IS NULL) OR (type='VALUE' AND ref_type IS NOT NULL)),
    CONSTRAINT category_ref_code UNIQUE(ref_type,code),
    CONSTRAINT category_id_ref UNIQUE(id,value_ref),
    CONSTRAINT category_group_fk FOREIGN KEY(ref_type) REFERENCES category(group_code)
);
COMMENT ON COLUMN category.description IS 'Mô tả mục đích hoặc hướng dẫn sử dụng danh mục';
CREATE INDEX idx_category_lookup ON category(ref_type,active,sort_order,id);
CREATE INDEX idx_category_parent ON category(ref_type,parent_id,active,sort_order,id);
CREATE INDEX idx_category_created_by ON category(created_by);
CREATE INDEX idx_category_updated_by ON category(updated_by);
CREATE INDEX idx_category_children ON category(parent_id,ref_type,sort_order,id) WHERE parent_id IS NOT NULL;

