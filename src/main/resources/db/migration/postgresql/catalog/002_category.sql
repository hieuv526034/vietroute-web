-- Chỉ diễn giải các quy tắc dữ liệu đã biết; không có SQL/Java động từ props.
CREATE FUNCTION category_props_valid(value jsonb,fields jsonb) RETURNS boolean LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE f jsonb; v jsonb; k text;
BEGIN
    IF jsonb_typeof(value)<>'object' OR jsonb_typeof(fields)<>'array' THEN RETURN false; END IF;
    IF value ? 'nameEn' AND (jsonb_typeof(value->'nameEn')<>'string' OR length(btrim(value->>'nameEn'))=0 OR length(value->>'nameEn')>120) THEN RETURN false; END IF;
    FOR k IN SELECT jsonb_object_keys(value) LOOP
        IF k<>'nameEn' AND NOT EXISTS(SELECT 1 FROM jsonb_array_elements(fields) e WHERE e->>'name'=k) THEN RETURN false; END IF;
    END LOOP;
    FOR f IN SELECT * FROM jsonb_array_elements(fields) LOOP
        k:=f->>'name'; v:=value->k;
        IF v IS NULL OR v='null'::jsonb THEN
            IF COALESCE((f->>'required')::boolean,false) THEN RETURN false; END IF;
            CONTINUE;
        END IF;
        IF jsonb_typeof(v)<>f->>'type' THEN RETURN false; END IF;
        IF f->>'type'='string' THEN
            IF COALESCE((f->>'required')::boolean,false) AND length(btrim(value->>k))=0 THEN RETURN false; END IF;
            IF f ? 'maxLength' AND length(value->>k)>(f->>'maxLength')::integer THEN RETURN false; END IF;
        ELSIF f->>'type'='number' THEN
            IF f ? 'min' AND (value->>k)::numeric<(f->>'min')::numeric THEN RETURN false; END IF;
            IF f ? 'max' AND (value->>k)::numeric>(f->>'max')::numeric THEN RETURN false; END IF;
            IF f ? 'scale' AND scale((value->>k)::numeric)>(f->>'scale')::integer THEN RETURN false; END IF;
        END IF;
        IF f ? 'values' AND NOT (f->'values' @> jsonb_build_array(v)) THEN RETURN false; END IF;
    END LOOP;
    RETURN true;
EXCEPTION WHEN OTHERS THEN RETURN false;
END $$;

CREATE FUNCTION category_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE g category%ROWTYPE; p category%ROWTYPE; parent_ref text;
BEGIN
    IF TG_OP='UPDATE' AND (NEW.id,NEW.code,NEW.type,NEW.ref_type,NEW.parent_id) IS DISTINCT FROM (OLD.id,OLD.code,OLD.type,OLD.ref_type,OLD.parent_id) THEN
        RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='category identity is immutable';
    END IF;
    IF NEW.type='VALUE' THEN
        SELECT * INTO g FROM category WHERE group_code=NEW.ref_type FOR SHARE;
        IF NOT FOUND OR (NEW.active AND NOT g.active) OR NOT category_props_valid(NEW.props,COALESCE(g.props->'fields','[]')) THEN
            RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='invalid category group or props';
        END IF;
        parent_ref:=COALESCE(g.props->>'parentRefType',CASE WHEN g.props->>'hierarchical'='true' THEN NEW.ref_type END);
        IF parent_ref IS NULL AND NEW.parent_id IS NOT NULL OR g.props->>'parentRefType' IS NOT NULL AND NEW.parent_id IS NULL THEN
            RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='invalid category parent';
        END IF;
        IF NEW.parent_id IS NOT NULL THEN
            SELECT * INTO p FROM category WHERE id=NEW.parent_id FOR SHARE;
            IF NOT FOUND OR p.type<>'VALUE' OR p.ref_type<>parent_ref OR (NEW.active AND NOT p.active) THEN
                RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='invalid category parent group';
            END IF;
        END IF;
    ELSE
        IF jsonb_typeof(COALESCE(NEW.props->'fields','[]'))<>'array' THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='invalid category field definitions'; END IF;
        IF EXISTS(
            SELECT 1 FROM category c LEFT JOIN category p ON p.id=c.parent_id
            WHERE c.type='VALUE' AND c.ref_type=NEW.code AND (
                NOT category_props_valid(c.props,COALESCE(NEW.props->'fields','[]'))
                OR ((NEW.props->>'parentRefType') IS NULL AND COALESCE(NEW.props->>'hierarchical','false')<>'true' AND c.parent_id IS NOT NULL)
                OR ((NEW.props->>'parentRefType') IS NOT NULL AND (p.id IS NULL OR p.ref_type<>NEW.props->>'parentRefType'))
            )
        ) THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='category rules conflict with existing items'; END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER category_guard BEFORE INSERT OR UPDATE ON category FOR EACH ROW EXECUTE FUNCTION category_guard();
