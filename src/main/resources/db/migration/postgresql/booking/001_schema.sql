CREATE UNIQUE INDEX IF NOT EXISTS idx_bookings_one_active_web ON bookings USING btree (customer_id) WHERE (((source_code)::text = 'WEB'::text) AND ((status)::text = ANY ((ARRAY['PENDING'::character varying, 'CONFIRMED'::character varying])::text[])));

