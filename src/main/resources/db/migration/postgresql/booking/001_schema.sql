-- booking: bảng, khóa chính, ràng buộc và index hiện hành.
-- Schema lấy từ LOCAL search_path; khóa ngoại được tạo sau toàn bộ cụm.

CREATE TABLE IF NOT EXISTS booking_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    booking_id bigint NOT NULL,
    trip_id bigint NOT NULL,
    carrier_id bigint NOT NULL,
    scope_id bigint NOT NULL,
    from_status character varying(20),
    to_status character varying(20) NOT NULL,
    event_type character varying(30) NOT NULL,
    amount numeric(15,2) DEFAULT 0 NOT NULL,
    note character varying(2000) DEFAULT ''::character varying NOT NULL,
    request_key uuid,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by bigint DEFAULT 0 NOT NULL
);

CREATE TABLE IF NOT EXISTS bookings (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code text GENERATED ALWAYS AS (('VR'::text || (id)::text)) STORED,
    trip_id bigint NOT NULL,
    carrier_id bigint NOT NULL,
    scope_id bigint NOT NULL,
    customer_id bigint,
    source_code character varying(20) NOT NULL,
    source_id bigint NOT NULL,
    source_type character varying(40) DEFAULT 'BOOKING_SOURCE'::character varying NOT NULL,
    pickup_stop_id bigint NOT NULL,
    dropoff_stop_id bigint NOT NULL,
    pickup_order integer NOT NULL,
    dropoff_order integer NOT NULL,
    seats integer NOT NULL,
    unit_price numeric(12,2) NOT NULL,
    total_price numeric(15,2) NOT NULL,
    contact_name character varying(120) NOT NULL,
    contact_phone character varying(30) NOT NULL,
    status character varying(20) DEFAULT 'PENDING'::character varying NOT NULL,
    request_key uuid NOT NULL,
    paid_amount numeric(15,2) DEFAULT 0 NOT NULL,
    refunded_amount numeric(15,2) DEFAULT 0 NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by bigint DEFAULT 0 NOT NULL,
    updated_by bigint DEFAULT 0 NOT NULL,
    version bigint DEFAULT 0 NOT NULL
);

