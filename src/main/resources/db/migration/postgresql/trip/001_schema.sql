-- Schema lấy từ LOCAL search_path; khóa ngoại được tạo sau toàn bộ cụm.

CREATE TABLE IF NOT EXISTS carrier_route_stops (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    route_id bigint NOT NULL,
    carrier_id bigint NOT NULL,
    scope_id bigint NOT NULL,
    location_id bigint NOT NULL,
    stop_order integer NOT NULL,
    arrival_offset_minutes integer NOT NULL,
    departure_offset_minutes integer NOT NULL,
    cumulative_fare numeric(12,2) NOT NULL,
    pickup_allowed boolean DEFAULT true NOT NULL,
    dropoff_allowed boolean DEFAULT true NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by bigint DEFAULT 0 NOT NULL,
    updated_by bigint DEFAULT 0 NOT NULL,
    version bigint DEFAULT 0 NOT NULL
);

CREATE TABLE IF NOT EXISTS carrier_routes (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    carrier_id bigint NOT NULL,
    scope_id bigint NOT NULL,
    code character varying(40) NOT NULL,
    name_vi character varying(160) NOT NULL,
    name_en character varying(160) NOT NULL,
    description character varying(2000) DEFAULT ''::character varying NOT NULL,
    active boolean DEFAULT true NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by bigint DEFAULT 0 NOT NULL,
    updated_by bigint DEFAULT 0 NOT NULL,
    version bigint DEFAULT 0 NOT NULL
);

CREATE TABLE IF NOT EXISTS carrier_trips (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    carrier_id bigint NOT NULL,
    scope_id bigint NOT NULL,
    route_id bigint NOT NULL,
    vehicle_id bigint NOT NULL,
    driver_id bigint NOT NULL,
    driver_user_id bigint NOT NULL,
    code character varying(40) NOT NULL,
    name_vi character varying(160) NOT NULL,
    name_en character varying(160) NOT NULL,
    plate_number character varying(20) NOT NULL,
    vehicle_type_id bigint NOT NULL,
    vehicle_type_name_vi character varying(120) NOT NULL,
    vehicle_type_name_en character varying(120) NOT NULL,
    driver_name character varying(120) NOT NULL,
    driver_phone character varying(30) NOT NULL,
    departure_at timestamp with time zone NOT NULL,
    end_at timestamp with time zone NOT NULL,
    capacity integer NOT NULL,
    status character varying(20) DEFAULT 'DRAFT'::character varying NOT NULL,
    operation_note character varying(2000) DEFAULT ''::character varying NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by bigint DEFAULT 0 NOT NULL,
    updated_by bigint DEFAULT 0 NOT NULL,
    version bigint DEFAULT 0 NOT NULL
);

CREATE TABLE IF NOT EXISTS trip_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    trip_id bigint NOT NULL,
    carrier_id bigint NOT NULL,
    scope_id bigint NOT NULL,
    stop_order integer,
    event_type character varying(30) NOT NULL,
    note character varying(2000) DEFAULT ''::character varying NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by bigint DEFAULT 0 NOT NULL
);

CREATE TABLE IF NOT EXISTS trip_segments (
    trip_id bigint NOT NULL,
    carrier_id bigint NOT NULL,
    scope_id bigint NOT NULL,
    segment_order integer NOT NULL,
    capacity integer NOT NULL,
    reserved_seats integer DEFAULT 0 NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_by bigint DEFAULT 0 NOT NULL,
    version bigint DEFAULT 0 NOT NULL
);

CREATE TABLE IF NOT EXISTS trip_stops (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    trip_id bigint NOT NULL,
    carrier_id bigint NOT NULL,
    scope_id bigint NOT NULL,
    location_id bigint NOT NULL,
    province_id bigint NOT NULL,
    stop_order integer NOT NULL,
    name_vi character varying(120) NOT NULL,
    name_en character varying(120) NOT NULL,
    address character varying(300) NOT NULL,
    latitude numeric(9,6) NOT NULL,
    longitude numeric(9,6) NOT NULL,
    scheduled_arrival_at timestamp with time zone NOT NULL,
    scheduled_departure_at timestamp with time zone NOT NULL,
    actual_arrival_at timestamp with time zone,
    actual_departure_at timestamp with time zone,
    cumulative_fare numeric(12,2) NOT NULL,
    pickup_allowed boolean NOT NULL,
    dropoff_allowed boolean NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by bigint DEFAULT 0 NOT NULL,
    updated_by bigint DEFAULT 0 NOT NULL,
    version bigint DEFAULT 0 NOT NULL
);

