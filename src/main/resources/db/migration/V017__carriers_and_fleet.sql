-- Nhà xe dùng scope riêng; trạng thái kinh doanh không tắt scope để vẫn xử lý dữ liệu tồn tại.
CREATE TABLE carriers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope_id BIGINT NOT NULL UNIQUE REFERENCES auth_data_scopes(id),
    code VARCHAR(40) NOT NULL UNIQUE CHECK (code ~ '^[A-Z][A-Z0-9]{2,39}$'),
    name VARCHAR(120) NOT NULL CHECK (length(trim(name)) > 0),
    phone VARCHAR(30) NOT NULL CHECK (length(trim(phone)) > 0),
    description VARCHAR(2000) NOT NULL DEFAULT '',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    logo_media_id BIGINT REFERENCES media_assets(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    updated_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    UNIQUE(id,scope_id)
);
CREATE INDEX idx_carriers_active_name ON carriers(active,name,id);
CREATE INDEX idx_carriers_logo ON carriers(logo_media_id);
CREATE INDEX idx_carriers_created_by ON carriers(created_by);
CREATE INDEX idx_carriers_updated_by ON carriers(updated_by);

-- FK ghép giữ loại danh mục ngay ở DB, không chỉ dựa validation trên service.
ALTER TABLE catalog_items ADD CONSTRAINT catalog_items_id_type_key UNIQUE(id,type);
CREATE TABLE carrier_vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carrier_id BIGINT NOT NULL,
    scope_id BIGINT NOT NULL,
    code VARCHAR(40) NOT NULL CHECK (code ~ '^[A-Z][A-Z0-9]{2,39}$'),
    plate_number VARCHAR(20) NOT NULL CHECK (plate_number ~ '^[A-Z0-9.-]{5,20}$'),
    plate_key VARCHAR(20) GENERATED ALWAYS AS (regexp_replace(plate_number,'[^A-Z0-9]','','g')) STORED NOT NULL UNIQUE CHECK (length(plate_key) >= 5),
    vehicle_type_id BIGINT NOT NULL,
    vehicle_type VARCHAR(40) NOT NULL DEFAULT 'VEHICLE_TYPE' CHECK (vehicle_type='VEHICLE_TYPE'),
    capacity INTEGER NOT NULL CHECK (capacity BETWEEN 1 AND 200),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    photo_media_id BIGINT REFERENCES media_assets(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    updated_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    FOREIGN KEY(carrier_id,scope_id) REFERENCES carriers(id,scope_id),
    FOREIGN KEY(vehicle_type_id,vehicle_type) REFERENCES catalog_items(id,type),
    UNIQUE(carrier_id,code),
    UNIQUE(id,carrier_id,scope_id)
);
CREATE INDEX idx_vehicles_carrier_state ON carrier_vehicles(carrier_id,active,id);
CREATE INDEX idx_vehicles_type ON carrier_vehicles(vehicle_type_id);
CREATE INDEX idx_vehicles_photo ON carrier_vehicles(photo_media_id);
CREATE INDEX idx_vehicles_created_by ON carrier_vehicles(created_by);
CREATE INDEX idx_vehicles_updated_by ON carrier_vehicles(updated_by);

CREATE TABLE carrier_drivers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carrier_id BIGINT NOT NULL,
    scope_id BIGINT NOT NULL,
    code VARCHAR(40) NOT NULL CHECK (code ~ '^[A-Z][A-Z0-9]{2,39}$'),
    name VARCHAR(120) NOT NULL CHECK (length(trim(name)) > 0),
    phone VARCHAR(30) NOT NULL CHECK (length(trim(phone)) > 0),
    user_id BIGINT UNIQUE REFERENCES auth_users(id) CHECK (user_id > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    updated_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    FOREIGN KEY(carrier_id,scope_id) REFERENCES carriers(id,scope_id),
    UNIQUE(carrier_id,code),
    UNIQUE(id,carrier_id,scope_id)
);
CREATE INDEX idx_drivers_carrier_state ON carrier_drivers(carrier_id,active,id);
CREATE INDEX idx_drivers_created_by ON carrier_drivers(created_by);
CREATE INDEX idx_drivers_updated_by ON carrier_drivers(updated_by);
