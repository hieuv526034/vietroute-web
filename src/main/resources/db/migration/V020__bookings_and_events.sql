-- Đặt theo chặng: PENDING không chiếm chỗ, xác nhận/hủy khóa trip trước booking/segments.
CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT GENERATED ALWAYS AS ('VR' || id::text) STORED UNIQUE,
    trip_id BIGINT NOT NULL,
    carrier_id BIGINT NOT NULL,
    scope_id BIGINT NOT NULL,
    customer_id BIGINT REFERENCES auth_users(id) CHECK(customer_id>0),
    source_code VARCHAR(20) NOT NULL CHECK(source_code IN('WEB','PHONE')),
    source_id BIGINT NOT NULL,
    source_type VARCHAR(40) NOT NULL DEFAULT 'BOOKING_SOURCE' CHECK(source_type='BOOKING_SOURCE'),
    pickup_stop_id BIGINT NOT NULL,
    dropoff_stop_id BIGINT NOT NULL,
    pickup_order INTEGER NOT NULL CHECK(pickup_order BETWEEN 1 AND 31),
    dropoff_order INTEGER NOT NULL CHECK(dropoff_order BETWEEN 2 AND 32 AND dropoff_order>pickup_order),
    seats INTEGER NOT NULL CHECK(seats BETWEEN 1 AND 200),
    unit_price NUMERIC(12,2) NOT NULL CHECK(unit_price>=0),
    total_price NUMERIC(15,2) NOT NULL CHECK(total_price=unit_price*seats),
    contact_name VARCHAR(120) NOT NULL CHECK(length(trim(contact_name))>0),
    contact_phone VARCHAR(30) NOT NULL CHECK(length(trim(contact_phone))>0),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN('PENDING','CONFIRMED','REJECTED','CANCELLED','COMPLETED')),
    request_key UUID NOT NULL UNIQUE,
    paid_amount NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK(paid_amount BETWEEN 0 AND total_price),
    refunded_amount NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK(refunded_amount BETWEEN 0 AND paid_amount),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    updated_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
    CHECK((source_code='WEB' AND customer_id IS NOT NULL) OR (source_code='PHONE' AND customer_id IS NULL)),
    FOREIGN KEY(trip_id,carrier_id,scope_id) REFERENCES carrier_trips(id,carrier_id,scope_id),
    FOREIGN KEY(source_id,source_type) REFERENCES catalog_items(id,type),
    FOREIGN KEY(pickup_stop_id,trip_id,carrier_id,scope_id) REFERENCES trip_stops(id,trip_id,carrier_id,scope_id),
    FOREIGN KEY(dropoff_stop_id,trip_id,carrier_id,scope_id) REFERENCES trip_stops(id,trip_id,carrier_id,scope_id),
    UNIQUE(id,trip_id,carrier_id,scope_id)
);
CREATE UNIQUE INDEX idx_bookings_one_active_web ON bookings(customer_id) WHERE source_code='WEB' AND status IN('PENDING','CONFIRMED');
CREATE INDEX idx_bookings_trip_status ON bookings(trip_id,status,id);
CREATE INDEX idx_bookings_carrier_status ON bookings(carrier_id,status,created_at,id);
CREATE INDEX idx_bookings_customer ON bookings(customer_id,created_at,id);
CREATE INDEX idx_bookings_pickup ON bookings(pickup_stop_id,status);
CREATE INDEX idx_bookings_dropoff ON bookings(dropoff_stop_id,status);
CREATE INDEX idx_bookings_source ON bookings(source_id);
CREATE INDEX idx_bookings_created_by ON bookings(created_by);
CREATE INDEX idx_bookings_updated_by ON bookings(updated_by);

CREATE TABLE booking_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    trip_id BIGINT NOT NULL,
    carrier_id BIGINT NOT NULL,
    scope_id BIGINT NOT NULL,
    from_status VARCHAR(20),
    to_status VARCHAR(20) NOT NULL CHECK(to_status IN('PENDING','CONFIRMED','REJECTED','CANCELLED','COMPLETED')),
    event_type VARCHAR(30) NOT NULL CHECK(event_type IN('CREATED','CONFIRMED','REJECTED','CANCELLED','COMPLETED','PAYMENT','REFUND')),
    amount NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK(amount>=0),
    note VARCHAR(2000) NOT NULL DEFAULT '',
    request_key UUID UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    FOREIGN KEY(booking_id,trip_id,carrier_id,scope_id) REFERENCES bookings(id,trip_id,carrier_id,scope_id)
);
CREATE INDEX idx_booking_events_parent ON booking_events(booking_id,id);
CREATE INDEX idx_booking_events_trip ON booking_events(trip_id,id);
CREATE INDEX idx_booking_events_created_by ON booking_events(created_by);
