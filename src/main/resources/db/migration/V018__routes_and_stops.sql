-- Mẫu tuyến một chiều; chuyến sau này sao chép snapshot, không sửa lịch sử theo mẫu.
CREATE TABLE carrier_routes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carrier_id BIGINT NOT NULL,
    scope_id BIGINT NOT NULL,
    code VARCHAR(40) NOT NULL CHECK (code ~ '^[A-Z][A-Z0-9]{2,39}$'),
    name_vi VARCHAR(160) NOT NULL CHECK (length(trim(name_vi))>0),
    name_en VARCHAR(160) NOT NULL CHECK (length(trim(name_en))>0),
    description VARCHAR(2000) NOT NULL DEFAULT '',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    updated_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version>=0),
    FOREIGN KEY(carrier_id,scope_id) REFERENCES carriers(id,scope_id),
    UNIQUE(carrier_id,code),
    UNIQUE(id,carrier_id,scope_id)
);
CREATE INDEX idx_routes_carrier_active ON carrier_routes(carrier_id,active,id);
CREATE INDEX idx_routes_created_by ON carrier_routes(created_by);
CREATE INDEX idx_routes_updated_by ON carrier_routes(updated_by);

CREATE TABLE carrier_route_stops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id BIGINT NOT NULL,
    carrier_id BIGINT NOT NULL,
    scope_id BIGINT NOT NULL,
    location_id BIGINT NOT NULL REFERENCES location_places(id),
    stop_order INTEGER NOT NULL CHECK (stop_order BETWEEN 1 AND 32),
    arrival_offset_minutes INTEGER NOT NULL CHECK (arrival_offset_minutes BETWEEN 0 AND 43200),
    departure_offset_minutes INTEGER NOT NULL CHECK (departure_offset_minutes BETWEEN arrival_offset_minutes AND 43200),
    cumulative_fare NUMERIC(12,2) NOT NULL CHECK (cumulative_fare>=0),
    pickup_allowed BOOLEAN NOT NULL DEFAULT TRUE,
    dropoff_allowed BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    updated_by BIGINT NOT NULL DEFAULT 0 REFERENCES auth_users(id),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version>=0),
    FOREIGN KEY(route_id,carrier_id,scope_id) REFERENCES carrier_routes(id,carrier_id,scope_id),
    UNIQUE(route_id,stop_order),
    UNIQUE(route_id,location_id)
);
CREATE INDEX idx_route_stops_location ON carrier_route_stops(location_id,route_id);
CREATE INDEX idx_route_stops_created_by ON carrier_route_stops(created_by);
CREATE INDEX idx_route_stops_updated_by ON carrier_route_stops(updated_by);
