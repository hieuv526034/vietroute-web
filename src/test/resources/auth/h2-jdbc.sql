-- Fixture JDBC cho các câu SQL portable. Migration/array/advisory lock vẫn kiểm bằng PostgreSQL thật.
CREATE TABLE auth_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(32) NOT NULL UNIQUE,
    display_name VARCHAR(120) NOT NULL,
    email VARCHAR(254) UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    previous_password_hash_1 VARCHAR(100),
    previous_password_hash_2 VARCHAR(100),
    bootstrap_scope_pending BOOLEAN NOT NULL DEFAULT FALSE,
    email_verified_at TIMESTAMP WITH TIME ZONE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    activation_pending BOOLEAN NOT NULL DEFAULT FALSE,
    must_change_password BOOLEAN NOT NULL DEFAULT TRUE,
    token_version BIGINT NOT NULL DEFAULT 0,
    failed_login_attempts INTEGER NOT NULL DEFAULT 0,
    locked_until TIMESTAMP WITH TIME ZONE,
    updated_by BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE auth_roles(code VARCHAR(24) PRIMARY KEY);
CREATE TABLE auth_user_roles(
    user_id BIGINT NOT NULL REFERENCES auth_users(id),
    role_code VARCHAR(24) NOT NULL REFERENCES auth_roles(code),
    scope_id BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY(user_id,role_code,scope_id)
);
CREATE TABLE auth_account_challenges(
    user_id BIGINT NOT NULL REFERENCES auth_users(id),
    purpose VARCHAR(20) NOT NULL,
    token_hash VARCHAR(100) NOT NULL,
    token_version BIGINT NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY(user_id,purpose)
);
