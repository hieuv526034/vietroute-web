package vn.vietroute;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;

import com.fasterxml.jackson.databind.ObjectMapper;
import java.sql.DriverManager;
import java.util.Map;
import java.util.Set;
import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.Test;
import vn.vietroute.auth.repo.AccessChangeRepo;
import vn.vietroute.support.TestJpa;

/** SQL history whitelist et rollback restent actifs même sans écran d'historique séparé. */
class AccessChangeHistoryTest {

    @Test
    void explicitMappingStatesDoNotSerializeAccountCredentialsAndRollbackRestoresHistory() throws Exception {
        try (
            var connection = DriverManager.getConnection(
                "jdbc:h2:mem:changes;MODE=PostgreSQL;DB_CLOSE_DELAY=-1",
                "sa",
                ""
            );
            var schema = connection.createStatement()
        ) {
            schema.execute("DROP TABLE IF EXISTS auth_access_changes");
            schema.execute(
                "CREATE TABLE auth_access_changes(id BIGINT GENERATED BY DEFAULT AS IDENTITY,event_type VARCHAR(64),target_kind VARCHAR(20),target_key VARCHAR(240),actor_id BIGINT,trace_id VARCHAR(64),before_state JSON,after_state JSON,created_by BIGINT,updated_by BIGINT)"
            );
            connection.setAutoCommit(false);
            var repo = new AccessChangeRepo(TestJpa.MANAGER, null);
            repo.append(
                connection,
                "USER_ROLES",
                "USER",
                "7",
                2,
                Map.of("roles", Set.of("OLD")),
                Map.of("roles", Set.of("NEW"))
            );
            try (var row = schema.executeQuery("SELECT before_state,after_state,actor_id FROM auth_access_changes")) {
                row.next();
                assertEquals(2, row.getLong(3));
                Assertions.assertTrue(row.getString(1).contains("OLD"));
                Assertions.assertTrue(row.getString(2).contains("NEW"));
            }
            connection.rollback();
            try (var row = schema.executeQuery("SELECT count(*) FROM auth_access_changes")) {
                row.next();
                assertEquals(0, row.getLong(1));
            }
        }
    }
}
